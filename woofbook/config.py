def reload_configuration(custom_config_path: Optional[str | Path] = None) -> WoofbookConfiguration:
    global ACTIVE_CONFIGURATION, DEFAULT_MODEL_DIRECTORY, DEFAULT_MODEL_WEIGHTS_PATH
    global DEFAULT_BOOKS_DIRECTORY, DEFAULT_AUDIO_OUTPUT_DIRECTORY, AUDIO_SAMPLE_RATE
    global AVAILABLE_VOICES, DEFAULT_VOICE, DEFAULT_OUTPUT_FORMAT, DEFAULT_AUDIO_BITRATE
    global DEFAULT_PARAGRAPH_PAUSE_SECONDS, DEFAULT_CHAPTER_PAUSE_SECONDS
    global DEFAULT_SYNTHESIS_TEMPERATURE, DEFAULT_END_OF_SPEECH_THRESHOLD, DEFAULT_MAX_RETRIES
    global DEFAULT_MODEL_DIR, DEFAULT_WEIGHTS_PATH, DEFAULT_BOOKS_DIR, DEFAULT_AUDIO_DIR
    global SAMPLE_RATE, DEFAULT_BITRATE, DEFAULT_PARAGRAPH_PAUSE, DEFAULT_CHAPTER_PAUSE
    global DEFAULT_TEMP, DEFAULT_EOS, DEFAULT_RETRIES

    ACTIVE_CONFIGURATION = parse_config_toml(custom_config_path)

    DEFAULT_MODEL_DIRECTORY = ACTIVE_CONFIGURATION.model_directory
    DEFAULT_MODEL_WEIGHTS_PATH = ACTIVE_CONFIGURATION.model_weights_path
    DEFAULT_BOOKS_DIRECTORY = ACTIVE_CONFIGURATION.books_directory
    DEFAULT_AUDIO_OUTPUT_DIRECTORY = ACTIVE_CONFIGURATION.audio_output_directory

    AUDIO_SAMPLE_RATE = ACTIVE_CONFIGURATION.sample_rate
    AVAILABLE_VOICES = ACTIVE_CONFIGURATION.available_voices
    DEFAULT_VOICE = ACTIVE_CONFIGURATION.voice
    DEFAULT_OUTPUT_FORMAT = ACTIVE_CONFIGURATION.output_format
    DEFAULT_AUDIO_BITRATE = ACTIVE_CONFIGURATION.audio_bitrate

    DEFAULT_PARAGRAPH_PAUSE_SECONDS = ACTIVE_CONFIGURATION.paragraph_pause_seconds
    DEFAULT_CHAPTER_PAUSE_SECONDS = ACTIVE_CONFIGURATION.chapter_pause_seconds

    DEFAULT_SYNTHESIS_TEMPERATURE = ACTIVE_CONFIGURATION.synthesis_temperature
    DEFAULT_END_OF_SPEECH_THRESHOLD = ACTIVE_CONFIGURATION.end_of_speech_threshold
    DEFAULT_MAX_RETRIES = ACTIVE_CONFIGURATION.max_retries

    DEFAULT_MODEL_DIR = DEFAULT_MODEL_DIRECTORY
    DEFAULT_WEIGHTS_PATH = DEFAULT_MODEL_WEIGHTS_PATH
    DEFAULT_BOOKS_DIR = DEFAULT_BOOKS_DIRECTORY
    DEFAULT_AUDIO_DIR = DEFAULT_AUDIO_OUTPUT_DIRECTORY
    SAMPLE_RATE = AUDIO_SAMPLE_RATE
    DEFAULT_BITRATE = DEFAULT_AUDIO_BITRATE
    DEFAULT_PARAGRAPH_PAUSE = DEFAULT_PARAGRAPH_PAUSE_SECONDS
    DEFAULT_CHAPTER_PAUSE = DEFAULT_CHAPTER_PAUSE_SECONDS
    DEFAULT_TEMP = DEFAULT_SYNTHESIS_TEMPERATURE
    DEFAULT_EOS = DEFAULT_END_OF_SPEECH_THRESHOLD
    DEFAULT_RETRIES = DEFAULT_MAX_RETRIES

    return ACTIVE_CONFIGURATION
